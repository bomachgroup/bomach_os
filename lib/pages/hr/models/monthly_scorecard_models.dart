class MonthlyScorecardMetric {
  final String metricName;
  final double currentValue;
  final double targetValue;
  final String unit;
  final String category;

  MonthlyScorecardMetric({
    required this.metricName,
    required this.currentValue,
    this.targetValue = 100,
    this.unit = '%',
    required this.category,
  });

  double getAchievementPercentage() {
    if (targetValue == 0) return 0;
    return (currentValue / targetValue) * 100;
  }

  bool isTargetMet() {
    return currentValue >= targetValue;
  }

  String getStatusColor() {
    final achievement = getAchievementPercentage();
    if (achievement >= 100) return '#16A34A'; // Green
    if (achievement >= 75) return '#FBBF24'; // Amber
    return '#EC2623'; // Red
  }
}

class MonthlyScorecard {
  final int id;
  final String employeeId;
  final String employeeName;
  final String employeeLevel;
  final int month;
  final int year;
  final double attendanceScore;
  final double taskDeliveryScore;
  final double reportAccuracyScore;
  final double brandContributionScore;
  final double trainingProgressScore;
  final double overallScore;
  final double targetScore;
  final double targetAchievement;
  final int ranking;
  final bool isAutoGenerated;
  final String notes;
  final DateTime? createdAt;
  final DateTime? updatedAt;

  MonthlyScorecard({
    required this.id,
    required this.employeeId,
    required this.employeeName,
    required this.employeeLevel,
    required this.month,
    required this.year,
    required this.attendanceScore,
    required this.taskDeliveryScore,
    required this.reportAccuracyScore,
    required this.brandContributionScore,
    required this.trainingProgressScore,
    required this.overallScore,
    required this.targetScore,
    required this.targetAchievement,
    required this.ranking,
    required this.isAutoGenerated,
    this.notes = '',
    this.createdAt,
    this.updatedAt,
  });

  /// Generate metrics list for UI iteration
  List<MonthlyScorecardMetric> get metrics => [
        MonthlyScorecardMetric(
          metricName: 'Attendance',
          currentValue: attendanceScore,
          category: 'Attendance',
        ),
        MonthlyScorecardMetric(
          metricName: 'Task Delivery',
          currentValue: taskDeliveryScore,
          category: 'Delivery',
        ),
        MonthlyScorecardMetric(
          metricName: 'Report Accuracy',
          currentValue: reportAccuracyScore,
          category: 'Accuracy',
        ),
        MonthlyScorecardMetric(
          metricName: 'Brand Contribution',
          currentValue: brandContributionScore,
          category: 'Contribution',
        ),
        MonthlyScorecardMetric(
          metricName: 'Training Progress',
          currentValue: trainingProgressScore,
          category: 'Training',
        ),
      ];

  String get formattedLevel {
    if (employeeLevel.isEmpty) return '';
    return employeeLevel[0].toUpperCase() + employeeLevel.substring(1);
  }

  String get initials {
    final parts = employeeName.trim().split(' ');
    if (parts.length >= 2) {
      return '${parts.first[0]}${parts.last[0]}'.toUpperCase();
    }
    return employeeName.isNotEmpty ? employeeName[0].toUpperCase() : '?';
  }

  String getScoreColor() {
    if (overallScore >= 85) return '#16A34A';
    if (overallScore >= 70) return '#FBBF24';
    return '#EC2623';
  }

  factory MonthlyScorecard.fromJson(Map<String, dynamic> json) {
    return MonthlyScorecard(
      id: json['id'] is int
          ? json['id']
          : int.tryParse(json['id']?.toString() ?? '0') ?? 0,
      employeeId: json['employee_id']?.toString() ?? '',
      employeeName: json['employee_name'] ?? '',
      employeeLevel: json['employee_level'] ?? '',
      month: json['month'] is int
          ? json['month']
          : int.tryParse(json['month']?.toString() ?? '1') ?? 1,
      year: json['year'] is int
          ? json['year']
          : int.tryParse(json['year']?.toString() ?? '2026') ?? 2026,
      attendanceScore:
          double.tryParse(json['attendance_score']?.toString() ?? '0') ?? 0,
      taskDeliveryScore:
          double.tryParse(json['task_delivery_score']?.toString() ?? '0') ?? 0,
      reportAccuracyScore:
          double.tryParse(json['report_accuracy_score']?.toString() ?? '0') ??
              0,
      brandContributionScore:
          double.tryParse(json['brand_contribution_score']?.toString() ?? '0') ??
              0,
      trainingProgressScore:
          double.tryParse(json['training_progress_score']?.toString() ?? '0') ??
              0,
      overallScore:
          double.tryParse(json['overall_score']?.toString() ?? '0') ?? 0,
      targetScore:
          double.tryParse(json['target_score']?.toString() ?? '0') ?? 0,
      targetAchievement:
          double.tryParse(json['target_achievement']?.toString() ?? '0') ?? 0,
      ranking: json['ranking'] is int
          ? json['ranking']
          : int.tryParse(json['ranking']?.toString() ?? '0') ?? 0,
      isAutoGenerated: json['is_auto_generated'] ?? false,
      notes: json['notes'] ?? '',
      createdAt: json['created_at'] != null
          ? DateTime.tryParse(json['created_at'])
          : null,
      updatedAt: json['updated_at'] != null
          ? DateTime.tryParse(json['updated_at'])
          : null,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'employee_id': employeeId,
      'employee_name': employeeName,
      'employee_level': employeeLevel,
      'month': month,
      'year': year,
      'attendance_score': attendanceScore,
      'task_delivery_score': taskDeliveryScore,
      'report_accuracy_score': reportAccuracyScore,
      'brand_contribution_score': brandContributionScore,
      'training_progress_score': trainingProgressScore,
      'overall_score': overallScore,
      'target_score': targetScore,
      'target_achievement': targetAchievement,
      'ranking': ranking,
      'is_auto_generated': isAutoGenerated,
      'notes': notes,
    };
  }
}
