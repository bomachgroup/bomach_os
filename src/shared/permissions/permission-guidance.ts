const resourceAreaEntries: [string, string][] = permissionAreas.flatMap((area) =>
  area.resources.map((resource) => [resource, area.id] as [string, string]),
)
const resourceAreaByName = new Map<string, string>(resourceAreaEntries)

export function getPermissionAreaId(resource: string) {
  return resourceAreaByName.get(resource) ?? 'other'
}

export function getPermissionSubjects(resource: string) {
  return resourceSubjects[resource] ?? resource.replaceAll('_', ' ')
}

export function getPermissionResourceLabel(resource: string) {
  return (
    resourceTitles[resource] ??
    resource.replaceAll('_', ' ').replace(/\b\w/g, (letter) => letter.toUpperCase())
  )
}

export function getPermissionGuidance(resource: string, action: string) {
  const specific = specificGuidance[`${resource}.${action}`]
  if (specific) return specific

  const actionCopy = actionGuidance[action]
  const subjects = getPermissionSubjects(resource)
  return actionCopy
    ? actionCopy(subjects)
    : `Use this action on ${subjects} within the scope assigned to this role.`
}
